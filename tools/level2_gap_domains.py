"""Classify the unmatched .text gaps by domain: gameplay/engine, render/media, UI/network/platform.

usage: python -I level2_gap_domains.py [top]

User 2026-11-23: "focus more on the remaining gap functions at least until we know these are not gameplay or
gameengine related". This takes every gap from level2_gaps.py (unmatched non-padding bytes between matched
functions, attributed to the TU of the neighbours), assigns the TU to a domain by its file name, and lists the
named function starts inside each gap from P/metadata/level2_symbols.json (function_start evidence).
The domain is a planning heuristic from file names, not proof; a gap at a TU boundary ('A | B') is classified
by its first TU and marked 'boundary'.
Output: P/docs/level2/GAP_DOMAINS_<utc>.md (new file) and W/analysis/level2/gap_domains_<utc>.json.
"""
import collections, datetime, json, os, re, subprocess, sys
P = r'D:\<project-folder>\Coding\RedAlert2'; W = r'D:\<work-root>\RedAlert2Temp'
top = int(sys.argv[1]) if len(sys.argv) > 1 else 60
DOM = [
    ('gameplay', r'techno|unit|infantry|building|bullet|aircraft|foot|drive|fly|walk|mech|ship|hover|jumpjet|rocket|tunnel|teleport|droppod|'
                 r'locomot|house|team|taskforce|script|trigger|tevent|taction|\btag|^map|mapgen|cell|zone|astar|path|anim|weapon|warhead|wave|'
                 r'ionblast|ion\.|radbeam|bomb|factory|bldgtype|builtype|unittype|inftype|infantrytype|aircrafttype|technotype|objecttype|objtype|'
                 r'object|abstract|rules|scenario|super|special|combat|logic|layer|crate|overlay|smudge|terrain|tiberium|veinhole|parasite|spawn|'
                 r'capture|temporal|mission|event|queue|cargo|radio|ccini|door|facing|coord|dropship|mpcoop|mpscore|multiplayer|siege|alliance|'
                 r'unholy|mpsiege|conquer|saveload|reinf|base|region|bridge|lightning|weather|veteran|armor|ai\.|tube|waypoint|sight|shroud|fog|'
                 r'radar|empulse|slave|bounce|particle|partsys|quat|matrix|vector|voxanim|hunt|hitpoint|targeting|threat|nuke|chrono'),
    ('render', r'tactical|display|dsurface|surface|blit|srfcache|voxel|voxlib|isotype|iso|palette|shape|font|text|convert|vqa|movie|bink|audio|'
               r'sound|voc|theme|draw|light|alpha|shadow|tint|ellipse|line|rect|zbuf|buffer|buff\.|bitmap|pcx|tga|cliprect|unvq|sos'),
    ('ui-net-platform', r'ownrdraw|dlg|dialog|menu|mainopt|gdlgsupp|progress|tooltip|mapsel|skirmish|egos|credits|wonline|wol|ipx|netdlg|connect|'
                        r'combuf|commbuf|session|modem|null|stats|sendfile|netshare|startup|init|wwmouse|mouse|keyboard|cd\.|copyprotection|'
                        r'debug|motlib|mono|file|mix|crc|lcw|lzo|xmp|random|ini|strtable|loadstr|wdt|worlddom|campaign|coopcamp|ldprgmgr|beacon|'
                        r'benchmark|timer|cdfile|registry|ime|ole|com|chat|lobby|ladder|gamespy|ipx|internet|winsock|wsproto'),
]


def domain(tu):
    b = os.path.basename(tu).lower()
    for name, rx in (DOM[0], DOM[2], DOM[1]):   # gameplay, then the specific UI/network/platform names, then render
        if re.search(rx, b):
            return name
    return 'unknown'


r = subprocess.run([sys.executable, '-I', os.path.join(W, 'tools', 'level2_gaps.py'), '100000'], capture_output=True, text=True, timeout=600)
gaps = []
for l in r.stdout.splitlines():
    m = re.match(r'^\s+(\d+)\s+0x([0-9a-f]+)\.\.0x([0-9a-f]+)\s+(.+)$', l)
    if m:
        gaps.append((int(m.group(1)), int(m.group(2), 16), int(m.group(3), 16), m.group(4).strip()))
seen = set(); uniq = []
for g in gaps:
    if (g[1], g[2]) not in seen:
        seen.add((g[1], g[2])); uniq.append(g)
S = json.load(open(os.path.join(P, 'metadata', 'level2_symbols.json'), encoding='utf-8'))
starts = sorted((int(v['address'], 16) - 0x400000, k) for k, v in S.items()
                if isinstance(v, dict) and v.get('evidence') == 'function_start' and 'address' in v)
rows, tot, cnt = [], collections.Counter(), collections.Counter()
for size, a, b, tu in uniq:
    first = tu.split('|')[0].strip()
    d = 'library' if first.startswith('<') else domain(first)
    names = [k for va, k in starts if a <= va < b][:8]
    rows.append(dict(bytes=size, start=hex(a), end=hex(b), tu=tu, domain=d, boundary='|' in tu, names=names))
    tot[d] += size; cnt[d] += 1
now = datetime.datetime.utcnow().strftime('%Y-%m-%dT%H%MZ')
json.dump(rows, open(os.path.join(W, 'analysis', 'level2', 'gap_domains_%s.json' % now), 'w', encoding='utf-8'), indent=1)
allb = sum(tot.values())
M = ['# Gap domains %s' % now, '', 'Generated by W/tools/level2_gap_domains.py (planning heuristic by TU file name; not proof).', '',
     '| Domain | Gap bytes | Share | Gaps |', '|---|---:|---:|---:|'] + \
    ['| %s | %d | %.1f %% | %d |' % (d, tot[d], 100.0 * tot[d] / allb, cnt[d]) for d, _ in tot.most_common()] + ['', '| total | %d | | %d |' % (allb, len(rows)), '']
pt = collections.defaultdict(collections.Counter)
for x in rows:
    pt[x['domain']][x['tu'].split('|')[0].strip()] += x['bytes']
for d, _ in tot.most_common():
    M += ['## %s: largest TUs' % d, ''] + ['- %s: %d bytes' % kv for kv in pt[d].most_common(15)] + ['']
M += ['## Largest gameplay gaps', '']
for x in sorted([x for x in rows if x['domain'] == 'gameplay'], key=lambda x: -x['bytes'])[:top]:
    M.append('- %d bytes %s..%s %s%s %s' % (x['bytes'], x['start'], x['end'], x['tu'], ' (boundary)' if x['boundary'] else '',
                                            ('names: ' + ', '.join(n[:60] for n in x['names'])) if x['names'] else ''))
md = os.path.join(P, 'docs', 'level2', 'GAP_DOMAINS_%s.md' % now)
if os.path.exists(md):
    raise SystemExit('refusing to overwrite ' + md)
open(md, 'w', encoding='utf-8').write('\n'.join(M) + '\n')
print('\n'.join(M[:40])); print('md:', md)
