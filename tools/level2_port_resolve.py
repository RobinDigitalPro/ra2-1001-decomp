"""Resolve ambiguous port matches through call/reference evidence.

usage: level2_port_resolve.py <check report json> <claims prefix> <tu dir> <port json> [<port json> ...]

When a byte-matching function with symbol S could sit at several addresses, the relocation bindings that other
checked functions require for S name the address their code actually references. If exactly one candidate
address of S is required that way and it is unclaimed, the function is proposed there. The object (TU) chosen
is the first in link order (alphabetical, case-insensitive) that compiles S, following VC6's COMDAT placement.
level2_check.py then verifies bytes and bindings as usual.
"""
import collections, json, os, sys
P = r'D:\<project-folder>\Coding\RedAlert2'
W = r'D:\<work-root>\RedAlert2Temp'
rep = json.load(open(sys.argv[1])); prefix, tudir = sys.argv[2], sys.argv[3]
OBJDIRS = [os.path.join(W, 'build', 'port', 'm85'), os.path.join(W, 'build', 'port', 'm85_try')]
req = collections.defaultdict(set)
for f in rep['functions']:
    for b in f.get('bindings', []):
        req[b['symbol']].add(int(b['address'], 16) - 0x400000)
# vtable slots: the original vtable (located through RTTI) names the address of every virtual function the
# compiled vtable COMDAT references
sys.path.insert(0, os.path.join(W, 'tools')); sys.path.insert(0, os.path.join(W, 'analysis', 'level2'))
import glob, level2_check
from coffmatch import Obj
B, secs = level2_check.image()
catalog = json.load(open(level2_check.RTTI))
for d in sys.argv[5 + 0:] if False else []:
    pass
for objdir in OBJDIRS:
    for op in glob.glob(os.path.join(objdir, '*.obj')):
        try:
            ob = Obj(open(op, 'rb').read())
        except Exception:
            continue
        for i, sy in ob.by_index.items():
            if not sy['name'].startswith('??_7') or sy['section'] <= 0:
                continue
            va = level2_check.vtable_address(catalog, sy['name'])
            if not va:
                continue
            sec = ob.sections[sy['section'] - 1]
            for off, si, typ in sec['relocs']:
                if typ != 6 or off < sy['value']:
                    continue
                k = off - sy['value']
                raw = level2_check.read(B, secs, va + k, 4)
                if raw:
                    req[ob.by_index[si]['name']].add(int.from_bytes(raw, 'little') - 0x400000)
funcs = json.load(open(os.path.join(P, 'metadata', 'level2_functions.json'), encoding='utf-8'))
claimed = {int(x['rva'], 16) for x in funcs}
files = {os.path.splitext(n)[0].lower(): n for n in os.listdir(os.path.join(P, *tudir.split('/')))}
objs = {}
for pj in sys.argv[4:]:
    objs.update(json.load(open(pj))['objects'])
out = collections.defaultdict(list); taken = set()
for o in sorted(objs, key=str.lower):
    for x in objs[o].get('functions', []):
        if len(x['rvas']) < 2 or x['symbol'].startswith('_$E'):
            continue
        c = [int(r, 16) for r in x['rvas'] if int(r, 16) in req.get(x['symbol'], ())]
        c = [a for a in c if a not in claimed and a not in taken]
        if len(c) == 1:
            taken.add(c[0])
            out[o].append(dict(rva=hex(c[0]), symbol=x['symbol'], name=x['symbol'], status='bytes_match_bindings_open'))
n = 0
for o, fl in out.items():
    src = files.get(os.path.splitext(o)[0].lower())
    if not src:
        continue
    json.dump(dict(tu=tudir + '/' + src, functions=fl, symbols={},
                   open=['generated by level2_port_resolve.py (ambiguous byte match resolved by the address other code references)']),
              open(os.path.join(W, 'analysis', 'level2', 'agents', '%s_%s.claims.json' % (prefix, os.path.splitext(o)[0])), 'w'), indent=0)
    n += len(fl)
print('resolved', n, 'in', len(out), 'objects')
