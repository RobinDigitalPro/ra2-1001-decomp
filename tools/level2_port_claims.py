"""Turn a level2_port_match.py result into claims files (one per upstream object).

usage: level2_port_claims.py <port json> <claims prefix> <tu dir relative to P, e.g. src/m85/src>

A function is proposed when (a) it byte-matches at exactly one address, or (b) it matches at several addresses
of which exactly one lies inside the address span of that object's unique matches (locality).  Addresses that
are already claimed, and static initializers ($E), are skipped.  level2_check.py verifies every claim.
"""
import json, os, sys
P = r'D:\<project-folder>\Coding\RedAlert2'
W = r'D:\<work-root>\RedAlert2Temp'
d = json.load(open(sys.argv[1]))
prefix, tudir = sys.argv[2], sys.argv[3]
funcs = json.load(open(os.path.join(P, 'metadata', 'level2_functions.json'), encoding='utf-8'))
claimed = {int(x['rva'], 16) for x in funcs}
files = {os.path.splitext(n)[0].lower(): n for n in os.listdir(os.path.join(P, *tudir.split('/')))}
taken = set(); total = 0; nfiles = 0
for o in sorted(d['objects'], key=str.lower):
    fs = [x for x in d['objects'][o].get('functions', []) if not x['symbol'].startswith('_$E')]
    uni = [(int(x['rvas'][0], 16), x['size']) for x in fs if len(x['rvas']) == 1]
    lo = hi = None
    if len(uni) >= 2:   # densest cluster of unique matches (COMDAT copies elsewhere would stretch a min/max span)
        pts = sorted(uni); best = []; cur = [pts[0]]
        for p in pts[1:]:
            if p[0] - (cur[-1][0] + cur[-1][1]) < 0x3000:
                cur.append(p)
            else:
                best = max(best, cur, key=lambda c: sum(x[1] for x in c)); cur = [p]
        best = max(best, cur, key=lambda c: sum(x[1] for x in c))
        lo, hi = best[0][0] - 0x20, best[-1][0] + best[-1][1] + 0x20
    out = []
    for x in fs:
        rv = [int(r, 16) for r in x['rvas']]
        if len(rv) > 1:
            if lo is None:
                continue
            rv = [a for a in rv if lo <= a < hi]
        rv = [a for a in rv if a not in claimed and a not in taken]
        if len(rv) != 1:
            continue
        taken.add(rv[0])
        out.append(dict(rva=hex(rv[0]), symbol=x['symbol'], name=x['symbol'], status='bytes_match_bindings_open'))
    src = files.get(os.path.splitext(o)[0].lower())
    if not out or not src:
        continue
    c = dict(tu=tudir + '/' + src, functions=out, symbols={},
             open=['generated by level2_port_claims.py (unique or locality-resolved byte match on 1.001)'])
    json.dump(c, open(os.path.join(W, 'analysis', 'level2', 'agents', '%s_%s.claims.json' % (prefix, os.path.splitext(o)[0])), 'w'), indent=0)
    total += len(out); nfiles += 1
print('claims files', nfiles, 'functions', total)
