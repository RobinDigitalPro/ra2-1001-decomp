"""Propose claims for unclaimed _$E static initializers / atexit destructors of given TUs.

usage: level2_claim_inits.py <claims prefix> <tu path relative to P> ...

The CURRENT source of each TU is compiled (private output dir build/level2/claim_inits). Every _$E function of the
object is byte-matched (relocations masked) against the 16-aligned addresses inside the TU's own address window
(its claimed functions' span, extended 0x4000 bytes before the first claim, because VC6 emits initializers first).
A function is proposed only when it matches at exactly one unclaimed address in that window and is not already
claimed by symbol. level2_check.py then verifies bytes and bindings as usual; claims are written per TU as
W/analysis/level2/agents/<prefix>_<module>.claims.json.
"""
import json, os, sys
P = r'D:\<project-folder>\Coding\RedAlert2'
W = r'D:\<work-root>\RedAlert2Temp'
sys.path.insert(0, os.path.join(W, 'analysis', 'level2')); sys.path.insert(0, os.path.join(W, 'tools'))
import level2_check as lc
from coffmatch import Obj, match_function

prefix = sys.argv[1]
B, secs = lc.image()
funcs = json.load(open(os.path.join(P, 'metadata', 'level2_functions.json'), encoding='utf-8'))
claimed = {int(f['rva'], 16) + 0x400000 for f in funcs}
outdir = os.path.join(W, 'build', 'level2', 'claim_inits'); os.makedirs(outdir, exist_ok=True)
total = 0
for tu in sys.argv[2:]:
    mine = [f for f in funcs if f['tu'] == tu]
    if not mine:
        print('no claims for', tu); continue
    have = {f['symbol'] for f in mine}
    addrs = sorted(int(f['rva'], 16) + 0x400000 for f in mine)
    # densest cluster (claims of COMDAT/ICF copies elsewhere would otherwise stretch the window)
    best, cur = [], [addrs[0]]
    for a in addrs[1:]:
        if a - cur[-1] < 0x3000:
            cur.append(a)
        else:
            best = max(best, cur, key=len); cur = [a]
    best = max(best, cur, key=len)
    lo, hi = (best[0] - 0x4000) & ~15, best[-1] + 0x1000
    obj, info = lc.compile_tu(tu, outdir)
    if info['returncode'] != 0:
        print('compile failed', tu); continue
    o = Obj(open(obj, 'rb').read())
    out = []
    for name, sym in o.symbols.items():
        if not name.startswith('_$E') or sym['value'] != 0 or name in have:
            continue
        raw = o.sections[sym['section'] - 1]['raw']
        masked = {r[0] + k for r in o.sections[sym['section'] - 1]['relocs'] for k in range(4)}
        hits = []
        for a in range(lo, hi, 16):
            if a in claimed:
                continue
            cur = lc.read(B, secs, a, len(raw))
            if any(cur[i] != raw[i] for i in range(min(8, len(raw))) if i not in masked):
                continue
            m = match_function(o, name, cur, a, lambda s: None)
            if m['byte_differences'] == 0 and not m['relocation_problems']:
                hits.append(a)
                if len(hits) > 1:
                    break
        if len(hits) == 1:
            out.append(dict(rva=hex(hits[0] - 0x400000), symbol=name, name='static initializer/destructor ' + name, status='bytes_match_bindings_open'))
            claimed.add(hits[0])
    if out:
        json.dump(dict(tu=tu, functions=out, symbols={}, open=['generated by level2_claim_inits.py (unique byte match of a _$E function inside the TU window)']),
                  open(os.path.join(W, 'analysis', 'level2', 'agents', '%s_%s.claims.json' % (prefix, os.path.splitext(os.path.basename(tu))[0])), 'w'), indent=0)
    total += len(out)
    print(tu, len(out), sum(0 for _ in out))
print('proposed', total)
