"""Generate TClassFactory<T> instances for every RTTI instance, with a minimal declaration of T
(AbstractClass-derived, exact sizeof from CreateInstance, constructor arity from its zero pushes),
compile with VC6 and produce claims for the slot functions that match byte for byte.

Writes P/src/ra2/templates/FACTORY_INSTANCES.cpp and W/analysis/level2/agents/FACTORY_INSTANCES.claims.json."""
import json, os, re, sys
P = r'D:\<project-folder>\Coding\RedAlert2'
W = r'D:\<work-root>\RedAlert2Temp'
sys.path.insert(0, os.path.join(W, 'analysis', 'level2'))
sys.path.insert(0, os.path.join(W, 'tools', 'portable', 'capstone-5.0.6'))
sys.path.insert(0, os.path.join(W, 'tools'))
import l2match, capstone, level2_check
from coffmatch import Obj, match_function
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
cat = json.load(open(os.path.join(W, 'analysis', 'level2', 'rtti_catalog.json')))
rows = []
for c in cat['classes']:
    m = re.match(r'\.\?AV\?\$TClassFactory@V([A-Za-z0-9_]+)@@@@$', c['type'])
    if not m:
        continue
    slots = c['vtables'][0]['slots']
    ci = int(slots[3], 16)
    txt = [(i.mnemonic, i.op_str, i) for i in md.disasm(l2match.orig(ci, 0x90), 0x400000 + ci)]
    size = ctor = None; args = []
    for k, (mn, op, ins) in enumerate(txt):
        if mn == 'push' and size is None and k + 1 < len(txt) and txt[k + 1][0] == 'call':
            size = int(op, 16)
        if mn == 'mov' and op == 'ecx, eax':
            j = k - 1
            while txt[j][0] == 'push':
                args.insert(0, txt[j][1]); j -= 1
            ctor = int(txt[k + 1][1], 16)
            break
    rows.append(dict(name=m.group(1), slots=slots, size=size, args=args, ctor=ctor))

lines = ['// Explicit instances of TClassFactory<T> for the COM-creatable classes listed in GAME.EXE RTTI.',
         '// Generated by W/tools/level2_factory_instances.py. Each T is a minimal stand-in declaration',
         '// (sizeof and constructor arity from GAME.EXE) until its real header exists.',
         '#include "../ABSTRACT.H"', '#include "../FACTORY.H"', '']
symbols = {}
for r in rows:
    if r['size'] is None or r['ctor'] is None or any(a != '0' for a in r['args']):
        r['skip_create'] = True
    params = ', '.join('void * a%d = 0' % i for i in range(len(r['args'])))
    pad = r['size'] - 0x24 if r['size'] else 4
    lines += ['class %s : public AbstractClass {' % r['name'], 'public:',
              '    %s(%s);' % (r['name'], params),
              '    virtual HRESULT __stdcall GetClassID(CLSID * pClassID);',
              '    virtual HRESULT __stdcall Load(IStream * pStm);',
              '    virtual HRESULT __stdcall Save(IStream * pStm, BOOL fClearDirty);',
              '    virtual int Kind_Of() const;', '    virtual int Size_Of() const;',
              '    char Data[0x%x];' % pad, '};',
              'template class TClassFactory<%s>;' % r['name'], '']
    if r['ctor'] is not None:
        mangled = '??0%s@@QAE@%s@Z' % (r['name'], 'PAX' * len(r['args']) if r['args'] else 'XZ')
        if r['args']:
            mangled = '??0%s@@QAE@%s@Z' % (r['name'], 'PAX' + ('0' * (len(r['args']) - 1)))
        else:
            mangled = '??0%s@@QAE@XZ' % r['name']
        symbols[mangled] = dict(address=hex(r['ctor']), evidence='function_start', note='constructor of %s (stand-in declaration)' % r['name'])
out = os.path.join(P, 'src', 'ra2', 'templates', 'FACTORY_INSTANCES.cpp')
open(out, 'w', newline='\r\n').write('\n'.join(lines) + '\n')
obj, info = level2_check.compile_tu('src/ra2/templates/FACTORY_INSTANCES.cpp', os.path.join(W, 'build', 'level2'))
if info['returncode'] != 0 or not os.path.exists(obj):
    print(info['output'][-3000:]); sys.exit(1)
o = Obj(open(obj, 'rb').read())
names = {0: '?QueryInterface@', 1: '?AddRef@', 2: '?Release@', 3: '?CreateInstance@', 4: '?LockServer@'}
claims = []
for r in rows:
    tag = '?$TClassFactory@V%s@@@@' % r['name']
    for slot, mname in names.items():
        if slot == 3 and r.get('skip_create'):
            continue
        rva = int(r['slots'][slot], 16)
        cands = [s for s in o.symbols if s.startswith(mname) and tag in s]
        for s in cands:
            rep = match_function(o, s, l2match.orig(rva, len(o.function(s)['raw'])), 0x400000 + rva, lambda x: None)
            if rep['byte_differences'] == 0 and not rep['relocation_problems']:
                claims.append(dict(rva=hex(rva), symbol=s, name='TClassFactory<%s> slot %d' % (r['name'], slot), status=rep['status']))
                break
symbols['_IID_IClassFactory'] = dict(address='0x79ab08', evidence='guid', guid='00000001-0000-0000-c000-000000000046')
json.dump(dict(tu='src/ra2/templates/FACTORY_INSTANCES.cpp', functions=claims, symbols=symbols),
          open(os.path.join(W, 'analysis', 'level2', 'agents', 'FACTORY_INSTANCES.claims.json'), 'w'), indent=1)
print('instances', len(rows), 'claims', len(claims), 'of', sum(5 - (1 if r.get('skip_create') else 0) for r in rows))
