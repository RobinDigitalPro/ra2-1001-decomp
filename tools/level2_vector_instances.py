"""Generate explicit VectorClass/DynamicVectorClass instances for pointer element types found in RTTI,
compile them with VC6 and produce a claims file for the slot functions that match byte for byte.

Writes P/src/ra2/templates/VECTOR_INSTANCES.cpp (result) and W/analysis/level2/agents/VECTOR_INSTANCES.claims.json.
Resize (slot 2) is skipped while it is open.  Original emitting TUs are not yet identified."""
import json, os, re, subprocess, sys
P = r'D:\<project-folder>\Coding\RedAlert2'
W = r'D:\<work-root>\RedAlert2Temp'
sys.path.insert(0, os.path.join(W, 'analysis', 'level2'))
import l2match
from coffmatch import Obj, match_function

cat = json.load(open(os.path.join(W, 'analysis', 'level2', 'rtti_catalog.json')))
PRIM = {'D': 'char', 'E': 'unsigned char', 'F': 'short', 'G': 'unsigned short', 'H': 'int', 'I': 'unsigned int',
        'J': 'long', 'K': 'unsigned long', 'M': 'float', 'N': 'double', '_N': 'bool', 'C': 'signed char'}
inst = {}
for c in cat['classes']:
    pm = re.match(r'\.\?AV\?\$(VectorClass|DynamicVectorClass)@(_N|[C-N])@@$', c['type'])
    if pm:
        inst.setdefault(('', pm.group(2)), {})[pm.group(1)] = c
        continue
    m = re.match(r'\.\?AV\?\$(VectorClass|DynamicVectorClass)@(P[AB][VU])([A-Za-z0-9_]+(?:@[A-Za-z0-9_]+)*)@@@@$', c['type'])
    if not m:
        continue
    kind, ptr, name = m.groups()
    inst.setdefault((ptr, name), {})[kind] = c


def decl(ptr, name):
    if ptr == '':
        return '', PRIM[name]
    if '@' in name:
        parts = name.split('@')
        if len(parts) != 2:
            return None, None
        return '', '%s::%s%s' % (parts[1], parts[0], ' const *' if ptr[1] == 'B' else ' *')
    parts = name.split('@')          # innermost first: Class@Namespace
    cls, ns = parts[0], parts[1:][::-1]
    key = 'class' if ptr[2] == 'V' else 'struct'
    d = '%s %s;' % (key, cls)
    for n in reversed(ns):
        d = 'namespace %s { %s }' % (n, d)
    full = '::'.join(ns + [cls])
    return d, full + (' const *' if ptr[1] == 'B' else ' *')


outers = {}
for (ptr, name) in inst:
    if ptr and '@' in name:
        parts = name.split('@')
        if len(parts) == 2:
            outers.setdefault(parts[1], set()).add((parts[0], ptr[2]))
lines0 = []
for o in sorted(outers):
    body = ' '.join('%s %s;' % ('class' if k == 'V' else 'struct', n) for n, k in sorted(outers[o]))
    lines0.append('class %s { public: %s };' % (o, body))
lines = ['// Explicit instances of the vector templates for pointer element types listed in GAME.EXE RTTI.',
         '// Generated by W/tools/level2_vector_instances.py. Original emitting TUs are not yet identified.',
         '#include "../VECTOR.H"', ''] + lines0 + ['']
types = []
for (ptr, name) in sorted(inst):
    d, t = decl(ptr, name)
    if t is None:
        continue
    if d and name.split('@')[0] not in outers:
        lines.append(d)
    types.append(((ptr, name), t))
lines.append('')
for (k, t) in types:
    if 'DynamicVectorClass' in inst[k]:
        lines.append('template class DynamicVectorClass<%s>;' % t)
    lines.append('template class VectorClass<%s>;' % t)
out = os.path.join(P, 'src', 'ra2', 'templates', 'VECTOR_INSTANCES.cpp')
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w', newline='\r\n').write('\n'.join(lines) + '\n')

sys.path.insert(0, os.path.join(W, 'tools'))
import level2_check
obj, info = level2_check.compile_tu('src/ra2/templates/VECTOR_INSTANCES.cpp', os.path.join(W, 'build', 'level2'))
if info['returncode'] != 0 or not os.path.exists(obj):
    print(info['output']); sys.exit(1)
o = Obj(open(obj, 'rb').read())
want = {0: '??_G', 1: '??8', 2: '?Resize@', 3: '?Clear@', 4: '?ID@', 5: '?ID@', 6: '?Fetch@'}
claims, seen = [], set()
for (k, t) in types:
    ptr, name = k
    for kind, c in inst[k].items():
        tag = ('?$%s@%s@@' % (kind, name)) if ptr == '' else ('?$%s@%s%s@@@@' % (kind, ptr, name))
        vt = c['vtables'][0]['slots']
        for slot, method in want.items():
            if slot >= len(vt):
                continue
            rva = int(vt[slot], 16)
            if rva in seen:
                continue
            cands = [s for s in o.symbols if s.startswith(method) and ('@' + tag) in s or (s.startswith(method) and tag in s)]
            for s in cands:
                code = o.function(s)['raw']
                rep = match_function(o, s, l2match.orig(rva, len(code)), 0x400000 + rva, lambda x: None)
                if rep['byte_differences'] == 0 and not rep['relocation_problems']:
                    claims.append(dict(rva=hex(rva), symbol=s, name='%s<%s> slot %d (template instance)' % (kind, t, slot),
                                       status=rep['status']))
                    seen.add(rva)
                    break
json.dump(dict(tu='src/ra2/templates/VECTOR_INSTANCES.cpp', functions=claims, symbols={}),
          open(os.path.join(W, 'analysis', 'level2', 'agents', 'VECTOR_INSTANCES.claims.json'), 'w'), indent=1)
print('pointer instances', len(types), 'claims', len(claims))
