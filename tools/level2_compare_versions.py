"""Side-by-side code comparison of stubborn functions: our failed version, the version that matched, the community version.

usage: python -I level2_compare_versions.py <out dir>

User 2026-11-24: "ik zou graag onze versies van de code en de community versie van de code tegen elkaar willen laten
vergelijken, en duidelijk aanduiden wat er in hun code telkens zo anders is dat wij niet konden vinden".
Inputs (read-only):
  - W/analysis/level2/jobstation_up/lessons_l1/history_before_after.zip: cases.json + before/<rva>__<tu> (our TU just
    before the integration that matched the function) and after/<rva>__<tu> (the current TU);
  - the recent gibbo ports: batch input folders jobstation_up/batch_44g_*, batch_47_*, batch_54_* (before) and the current P TU (after);
  - community sources: W/analysis/level2/ctx44g/gibbo*.cpp (gibbo101 YR 1.001) and ctx42/meastes1006_*.cpp (meastes RA2 1.006).
For every case the function body is cut out of each version (by Class::Name, brace matched) and written as
<out>/<rva>_<name>.md with three unified diffs: before -> after (what changed to make it match), community -> after
(how our final form differs from theirs) and before -> community. <out>/INDEX.md lists all cases with changed-line counts.
"""
import difflib, glob, io, json, os, re, sys, zipfile
P = r'D:\<project-folder>\Coding\RedAlert2'; L = r'D:\<work-root>\RedAlert2Temp\analysis\level2'
out = sys.argv[1]; os.makedirs(out, exist_ok=True)
F = json.load(open(os.path.join(P, 'metadata', 'level2_functions.json'), encoding='utf-8'))
claims = {int(f['rva'], 16): f for f in F}


def parts(sym):
    m = re.match(r'^\?\?([01])([^@]+)@', sym)
    if m:
        return (m.group(2), ('~' if m.group(1) == '1' else '') + m.group(2))
    m = re.match(r'^\?([^@?]+)@([^@]*)@', sym)
    if m:
        return (m.group(2) or None, m.group(1))
    return (None, None)


def cut(src, cls, name):
    if not name:
        return None
    pat = (re.escape(cls) + r'\s*::\s*' if cls else r'(?<![:\w~])') + re.escape(name) + r'\s*\([^;{]*\)\s*(const)?\s*(//[^\n]*)?\s*\{'
    for m in re.finditer(pat, src):
        s = src.rfind('\n', 0, m.start()) + 1
        i, d = m.end(), 1
        while d and i < len(src):
            d += {'{': 1, '}': -1}.get(src[i], 0); i += 1
        return src[s:i]
    return None


def community(tu, cls, name):
    b = os.path.basename(tu).lower()
    for f in sorted(glob.glob(os.path.join(L, 'ctx44g', 'gibbo*_' + b)), reverse=True) + glob.glob(os.path.join(L, 'ctx42', 'meastes1006_' + b)):
        src = open(f, encoding='latin-1').read()
        body = cut(src, cls, name)
        if body:
            return os.path.basename(f), body
    return None, None


def diff(a, b, na, nb):
    if a is None or b is None:
        return '(not available)\n', 0
    d = list(difflib.unified_diff(a.split('\n'), b.split('\n'), na, nb, n=2, lineterm=''))
    return ('\n'.join(d) or '(identical)') + '\n', sum(1 for l in d if l[:1] in '+-' and not l.startswith(('+++', '---')))


cases = []
z = zipfile.ZipFile(os.path.join(L, 'jobstation_up', 'lessons_l1', 'history_before_after.zip'))
meta = json.loads(z.read('cases.json'))
for c in meta:
    if not c.get('before'):
        continue
    b = os.path.basename(c['tu'])
    cases.append((int(c['rva'], 16), c['function'], c['tu'],
                  z.read('before/%s__%s' % (c['rva'], b)).decode('latin-1'), z.read('after/%s__%s' % (c['rva'], b)).decode('latin-1'),
                  'history: ' + (c.get('claims_file') or '')))
for bat, rvas in (('batch_44g_*', [0x7a900, 0x18e7a0, 0x281740, 0x300c60, 0x120fd0, 0x29d4c0]), ('batch_47_*', [0x163130]), ('batch_54_*', [0x166110, 0x219e20])):
    d = glob.glob(os.path.join(L, 'jobstation_up', bat))
    for r in rvas:
        f = claims.get(r)
        if not d or not f:
            continue
        x = [y for y in os.listdir(d[0]) if y.lower() == os.path.basename(f['tu']).lower()]
        if x:
            cases.append((r, f['symbol'], f['tu'], open(os.path.join(d[0], x[0]), encoding='latin-1').read(),
                          open(os.path.join(P, f['tu'].replace('/', os.sep)), encoding='latin-1').read(), 'recent port: ' + bat))
idx = ['# Code comparison of stubborn functions', '', 'Generated by W/tools/level2_compare_versions.py. Per case: our failed version (before), the version that matched (after) and the community version where one exists.', '',
       '| RVA | Function | TU | Source | before->after changed lines | community | community->after changed lines |', '|---|---|---|---|---:|---|---:|']
seen = set()
for r, fn, tu, before, after, origin in cases:
    if r in seen:
        continue
    seen.add(r)
    f = claims.get(r); sym = f['symbol'] if f else fn
    cls, name = parts(sym)
    b1, b2 = cut(before, cls, name), cut(after, cls, name)
    cf, cb = community(tu, cls, name)
    d1, n1 = diff(b1, b2, 'ours before', 'ours matched')
    d2, n2 = diff(cb, b2, 'community', 'ours matched')
    d3, _ = diff(b1, cb, 'ours before', 'community')
    nm = re.sub(r'\W+', '_', (cls + '__' if cls else '') + (name or fn))[:60]
    fnm = '%s_%s.md' % (hex(r), nm)
    open(os.path.join(out, fnm), 'w', encoding='utf-8').write(
        '# %s %s (%s)\n\nOrigin: %s. Community source: %s.\n\n## 1. What changed to make it match (ours before -> ours matched)\n\n```diff\n%s```\n\n## 2. Our matched form against the community form\n\n```diff\n%s```\n\n## 3. Our failed form against the community form\n\n```diff\n%s```\n'
        % (hex(r), sym, tu, origin, cf or 'none found', d1, d2, d3))
    idx.append('| %s | %s | %s | %s | %s | %s | %s |' % (hex(r), (name or fn)[:40], os.path.basename(tu), origin.split(':')[0], n1 if b1 and b2 else '-', cf or '-', n2 if cb and b2 else '-'))
open(os.path.join(out, 'INDEX.md'), 'w', encoding='utf-8').write('\n'.join(idx) + '\n')
print(len(seen), 'cases ->', out)
